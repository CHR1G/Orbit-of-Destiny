/* Rebuild components/threeui/liquid-metal-button.source.js from the vendored
 * html.
 *
 * The component ThreeUI publishes imports its markup with
 * `import src from "./liquid-metal-button.html?raw"`. That import is what this
 * project cannot honour: Turbopack has no module type for `.html`, and the
 * build stops with "Unknown module type" — measured, not assumed
 * (`.probe/dev3000.log`, 2026-09-23). Next's webpack config has no `?raw`
 * resource-query rule either, so registering a loader would have to be redone
 * for each bundler.
 *
 * So the html stays in the repository exactly as published — that file is the
 * authority — and this script projects it into an ES module holding the same
 * bytes as a JSON-escaped string, which every bundler already knows how to
 * read. Escaping is the only transform: the string the component receives is
 * byte-identical to the file, so every `.replace()` the component performs on
 * it still lands.
 *
 * Run: node scripts/build-threeui-source.mjs
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "components", "threeui");

/* Every vendored file this project ships, with the hash ThreeUI publishes for
 * it. A published update changes these, and the check below is what turns
 * "someone overwrote the file" into a failure instead of a mystery. */
const VENDORED = {
  "liquid-metal-button.html": {
    role: "canonical-source",
    sha256: "76624e881a3aecbd79b473d9c51f53c7157d47052abd0f9dc28fefd223b0a819",
  },
};

let failed = false;
for (const [name, want] of Object.entries(VENDORED)) {
  const bytes = readFileSync(join(dir, name));
  const got = createHash("sha256").update(bytes).digest("hex");
  const ok = got === want.sha256;
  if (!ok) failed = true;
  console.log(`${ok ? "ok  " : "FAIL"} ${name} (${want.role}) ${got}`);
}
if (failed) {
  console.error("\nA vendored file does not match its published hash. Fix that before building.");
  process.exit(1);
}

const html = readFileSync(join(dir, "liquid-metal-button.html"), "utf8");
const sha = createHash("sha256").update(html, "utf8").digest("hex");
const out = `/* GENERATED by scripts/build-threeui-source.mjs — do not edit by hand.
 *
 * Verbatim text of components/threeui/liquid-metal-button.html, the
 * canonical source published at https://threeui.com/source-code/liquid-metal-button.json
 *   id          liquid-metal-button
 *   revision    sha256 ${sha}
 *
 * The component's own source imports this file's html twin through the ?raw
 * resource query, which Turbopack in this project cannot resolve; see the
 * generator for why this projection exists instead. Only JSON escaping
 * differs — same bytes in, same bytes out — so the string-replacements
 * LiquidMetalButton makes against its markup behave identically here.
 */
const LIQUID_METAL_BUTTON_HTML = ${JSON.stringify(html)};

export default LIQUID_METAL_BUTTON_HTML;
`;
writeFileSync(join(dir, "liquid-metal-button.source.js"), out);
console.log(`\nwrote liquid-metal-button.source.js (${html.length} chars of markup embedded)`);
