/* ------------------------------------------------------------------ *
 * Build the 56 Minor Arcana.
 *
 * Artwork is the real deck in /public/tarot:
 *   minor_<suit>_<NN>.webp    NN = 01 Ace .. 14 King, matching RANKS order
 * To swap the art, drop files at those names — nothing here needs to
 * change. (An earlier revision generated placeholder SVG data URIs here;
 * that is gone now that the real art has landed.)
 * ------------------------------------------------------------------ */
export const MINOR_ARCANA = SUITS.flatMap((suit) =>
  RANKS.map((rank, ri) => {
    const m = MINOR_MEANINGS[suit.id][rank.id];
    const nn = String(ri + 1).padStart(2, "0");
    return {
      arcana: "minor",
      suit: suit.id,
      suitZh: suit.zh,
      element: suit.element,
      rank: rank.id,
      // `num` is what gets shown in the corner chip and share card.
      num: rank.mark,
      zh: `${suit.zh}${rank.zh}`,
      en: `${rank.en} of ${suit.en}`,
      kw: m.kw,
      up: m.up,
      down: m.down,
      tone: rank.tone,
      img: `/tarot/minor_${suit.file}_${nn}.webp`,
    };
  }),
);

export const SUIT_BY_ID = Object.fromEntries(SUITS.map((s) => [s.id, s]));
